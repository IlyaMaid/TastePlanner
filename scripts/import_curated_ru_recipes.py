def resolve_db_url(db_url: Optional[str]) -> str:
    if db_url:
        return db_url
    env_db_url = os.getenv("DATABASE_URL")
    if env_db_url:
        return env_db_url
    backend_env_path = PROJECT_ROOT / "backend/.env"
    if backend_env_path.exists():
        for line in backend_env_path.read_text(encoding="utf-8").splitlines():
            if line.startswith("DATABASE_URL="):
                return line.split("=", 1)[1].strip()
    raise SystemExit("--db-url is required unless DATABASE_URL is available.")


def ensure_schema(conn) -> None:
    for name in (
        "ingredient_prices_migration.sql",
        "recipe_steps_translation_migration.sql",
        "recipe_quality_migration.sql",
    ):
        path = PROJECT_ROOT / "postgress" / name
        if path.exists():
            conn.execute(text(path.read_text(encoding="utf-8")))


def recipe_nutrition(recipe: dict) -> dict[str, float]:
    totals = {"calories": 0.0, "protein": 0.0, "fat": 0.0, "carbs": 0.0}
    for key, grams in recipe["ingredients"]:
        info = INGREDIENTS[key]
        totals["calories"] += info.calories * grams / 100
        totals["protein"] += info.protein * grams / 100
        totals["fat"] += info.fat * grams / 100
        totals["carbs"] += info.carbs * grams / 100
    return {key: round(value / recipe["servings"], 1) for key, value in totals.items()}


def ingredient_cost(recipe: dict) -> float:
    return round(
        sum(INGREDIENTS[key].price * grams / 100 for key, grams in recipe["ingredients"]),
        1,
    )


def export_csv(path: Path = DEFAULT_DATASET_PATH) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as file:
        writer = csv.DictWriter(
            file,
            fieldnames=[
                "source_recipe_id",
                "title",
                "description",
                "total_minutes",
                "servings",
                "calories",
                "protein",
                "fat",
                "carbs",
                "estimated_cost_rub",
                "region_code",
                "tags_json",
                "ingredients_json",
                "steps_json",
            ],
        )
        writer.writeheader()
        for recipe in RECIPES:
            nutrition = recipe_nutrition(recipe)
            writer.writerow(
                {
                    **{key: recipe[key] for key in ("source_recipe_id", "title", "description", "total_minutes", "servings", "region_code")},
                    **nutrition,
                    "estimated_cost_rub": ingredient_cost(recipe),
                    "tags_json": json.dumps(recipe["tags"], ensure_ascii=False),
                    "ingredients_json": json.dumps(recipe["ingredients"], ensure_ascii=False),
                    "steps_json": json.dumps(recipe["steps"], ensure_ascii=False),
                }
            )


def get_or_create_ingredient(conn, key: str) -> int:
    info = INGREDIENTS[key]
    row = conn.execute(
        text("SELECT id FROM ingredients WHERE canonical_name = :name"),
        {"name": key},
    ).first()
    if row:
        ingredient_id = int(row[0])
        conn.execute(
            text(
                """
                UPDATE ingredients
                SET
                    display_name_ru = :display_name_ru,
                    category = :category,
                    calories_per_100g = :calories,
                    protein_per_100g = :protein,
                    fat_per_100g = :fat,
                    carbs_per_100g = :carbs,
                    price_per_100g_rub = :price,
                    price_source = 'curated_ru',
                    price_updated_at = CURRENT_DATE,
                    is_active = TRUE
                WHERE id = :id
                """
            ),
            {"id": ingredient_id, **info.__dict__},
        )
    else:
        row = conn.execute(
            text(
                """
                INSERT INTO ingredients (
                    canonical_name,
                    display_name_ru,
                    category,
                    calories_per_100g,
                    protein_per_100g,
                    fat_per_100g,
                    carbs_per_100g,
                    price_per_100g_rub,
                    price_source,
                    price_updated_at,
                    is_active
                )
                VALUES (
                    :canonical_name,
                    :display_name_ru,
                    :category,
                    :calories,
                    :protein,
                    :fat,
                    :carbs,
                    :price,
                    'curated_ru',
                    CURRENT_DATE,
                    TRUE
                )
                RETURNING id
                """
            ),
            {"canonical_name": key, **info.__dict__},
        ).first()
        ingredient_id = int(row[0])

    for alias in (info.display_name_ru, key, *info.aliases):
        conn.execute(
            text(
                """
                INSERT INTO ingredient_aliases (ingredient_id, alias)
                VALUES (:ingredient_id, :alias)
                ON CONFLICT (alias) DO NOTHING
                """
            ),
            {"ingredient_id": ingredient_id, "alias": alias.casefold()},
        )
    return ingredient_id


def import_recipes(db_url: str) -> int:
    engine = create_engine(db_url)
    inserted = 0
    with engine.begin() as conn:
        ensure_schema(conn)
        for recipe in RECIPES:
            nutrition = recipe_nutrition(recipe)
            row = conn.execute(
                text(
                    """
                    INSERT INTO recipes (
                        source,
                        source_recipe_id,
                        title,
                        description,
                        steps_json,
                        translated_title,
                        translated_description,
                        translated_steps_json,
                        total_minutes,
                        servings,
                        calories,
                        protein,
                        fat,
                        carbs,
                        rating,
                        region_code,
                        language,
                        is_user_facing,
                        quality_score,
                        tags_json
                    )
                    VALUES (
                        'curated_ru',
                        :source_recipe_id,
                        :title,
                        :description,
                        CAST(:steps_json AS jsonb),
                        :title,
                        :description,
                        CAST(:steps_json AS jsonb),
                        :total_minutes,
                        :servings,
                        :calories,
                        :protein,
                        :fat,
                        :carbs,
                        4.80,
                        :region_code,
                        'ru',
                        TRUE,
                        0.950,
                        CAST(:tags_json AS jsonb)
                    )
                    ON CONFLICT (source, source_recipe_id)
                    DO UPDATE SET
                        title = EXCLUDED.title,
                        description = EXCLUDED.description,
                        steps_json = EXCLUDED.steps_json,
                        translated_title = EXCLUDED.translated_title,
                        translated_description = EXCLUDED.translated_description,
                        translated_steps_json = EXCLUDED.translated_steps_json,
                        total_minutes = EXCLUDED.total_minutes,
                        servings = EXCLUDED.servings,
                        calories = EXCLUDED.calories,
                        protein = EXCLUDED.protein,
                        fat = EXCLUDED.fat,
                        carbs = EXCLUDED.carbs,
                        rating = EXCLUDED.rating,
                        region_code = EXCLUDED.region_code,
                        language = EXCLUDED.language,
                        is_user_facing = EXCLUDED.is_user_facing,
                        quality_score = EXCLUDED.quality_score,
                        tags_json = EXCLUDED.tags_json
                    RETURNING id
                    """
                ),
                {
                    "source_recipe_id": recipe["source_recipe_id"],
                    "title": recipe["title"],
                    "description": recipe["description"],
                    "steps_json": json.dumps(recipe["steps"], ensure_ascii=False),
                    "total_minutes": recipe["total_minutes"],
                    "servings": recipe["servings"],
                    "region_code": recipe["region_code"],
                    "tags_json": json.dumps(recipe["tags"], ensure_ascii=False),
                    **nutrition,
                },
            ).first()
            recipe_id = int(row[0])
            conn.execute(
                text("DELETE FROM recipe_ingredients WHERE recipe_id = :recipe_id"),
                {"recipe_id": recipe_id},
            )
            ingredient_names: list[str] = []
            for key, grams in recipe["ingredients"]:
                ingredient_id = get_or_create_ingredient(conn, key)
                display_name = INGREDIENTS[key].display_name_ru
                ingredient_names.append(display_name)
                conn.execute(
                    text(
                        """
                        INSERT INTO recipe_ingredients (
                            recipe_id,
                            ingredient_id,
                            raw_text,
                            quantity,
                            unit
                        )
                        VALUES (
                            :recipe_id,
                            :ingredient_id,
                            :raw_text,
                            :quantity,
                            'g'
                        )
                        """
                    ),
                    {
                        "recipe_id": recipe_id,
                        "ingredient_id": ingredient_id,
                        "raw_text": f"{display_name} - {grams} г",
                        "quantity": grams,
                    },
                )
            conn.execute(
                text(
                    """
                    UPDATE recipes
                    SET translated_ingredients_json = CAST(:ingredients AS jsonb)
                    WHERE id = :recipe_id
                    """
                ),
                {
                    "recipe_id": recipe_id,
                    "ingredients": json.dumps(ingredient_names, ensure_ascii=False),
                },
            )
            inserted += 1
    return inserted


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Import curated Russian recipes.")
    parser.add_argument("--db-url", default=None)
    parser.add_argument("--export-csv", action="store_true")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    export_csv()
    if args.export_csv:
        print(f"Exported curated dataset to {DEFAULT_DATASET_PATH}")
        return
    count = import_recipes(resolve_db_url(args.db_url))
    print(f"Imported {count} curated Russian recipes.")
    print(f"Dataset CSV: {DEFAULT_DATASET_PATH}")


if __name__ == "__main__":
    main()
